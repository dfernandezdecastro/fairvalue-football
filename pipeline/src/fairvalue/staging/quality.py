"""Generate reports/staging/data_quality.md from the staging tables.

Only aggregate counts are written (no raw rows), so the report can be committed.
"""

from __future__ import annotations

import json

import pandas as pd

from fairvalue.config import BIG5, REPO_ROOT, STAGING_DIR
from fairvalue.staging.build import read_staging

REPORT = REPO_ROOT / "reports" / "staging" / "data_quality.md"


def _pct(n: int, d: int) -> str:
    return f"{n:,} ({n / d:.1%})" if d else "0"


def build_report() -> str:
    manifest = json.loads((STAGING_DIR / "manifest.json").read_text(encoding="utf-8"))
    players = read_staging("players")
    t = read_staging("transfers")
    v = read_staging("valuations")
    us = read_staging("understat_player_seasons")
    cov = read_staging("understat_coverage")
    m = read_staging("understat_tm_matches")
    cls = read_staging("club_league_seasons")
    m = m.merge(us[["understat_id", "league", "season", "minutes"]], on=["understat_id", "league", "season"])

    lines = [
        "# Staging data quality",
        "",
        f"*Generated by `fairvalue quality` from staging built {manifest['created_at']} "
        f"(pipeline {manifest['pipeline_version']}). Aggregates only.*",
        "",
        "## Source identity",
        "",
        f"- Transfermarkt snapshot sha256 `{manifest['sources']['transfermarkt_zip_sha256'][:16]}…`, "
        f"cutoff {manifest['sources']['transfermarkt_cutoff']}",
        f"- Understat archive cache sha256 `{manifest['sources']['understat_cache_sha256'][:16]}…`",
        "",
        "## Row counts",
        "",
        pd.Series(manifest["row_counts"]).rename("rows").to_frame().to_markdown(),
        "",
        "## Players",
        "",
        f"- Missing date of birth: {_pct(int(players.date_of_birth.isna().sum()), len(players))}",
        f"- Missing or 'Missing' position: "
        f"{_pct(int((players.position.isna() | (players.position == 'Missing')).sum()), len(players))}",
        "- Position is the **current** Transfermarkt label (snapshot); historical position must come "
        "from Understat's per-season position where available.",
        "- Removed at ingest (snapshot-only, leakage risk): caps, contract expiry, current club, latest "
        "market value, agent.",
        "",
        "## Transfers (to cutoff)",
        "",
        t.move_type.value_counts().rename("transfers").to_frame().to_markdown(),
        "",
    ]
    paid = t[(t.move_type == "paid_transfer") & (t.date >= "2015-07-01")]
    n = len(paid)
    buyer_known = int(paid.to_competition_id.notna().sum())
    seller_known = int(paid.from_competition_id.notna().sum())
    big5 = int((paid.to_competition_id.isin(BIG5) | paid.from_competition_id.isin(BIG5)).sum())
    lines += [
        "Paid transfers since 2015/16 (excluding probable paid loans):",
        "",
        f"- Total: {n:,}",
        f"- Buyer league known (covered top flight): {_pct(buyer_known, n)}",
        f"- Seller league known: {_pct(seller_known, n)}",
        f"- Big-five club involved: {_pct(big5, n)}",
        "- Fees are as reported by Transfermarkt: no disclosed/estimated flag, add-ons not separated, "
        "paid loan fees recorded as 0.",
        "",
        "## Market valuations",
        "",
        f"- {len(v):,} valuations for {v.player_id.nunique():,} players, "
        f"{v.date.min().date()} to {v.date.max().date()}",
        f"- Median valuations per player: {v.groupby('player_id').size().median():.0f}",
        "",
        "## League coverage (club-season league assignments from fixtures)",
        "",
        cls.groupby("competition_id")
        .season.agg(["min", "max", "nunique"])
        .rename(columns={"min": "first", "max": "last", "nunique": "seasons"})
        .to_markdown(),
        "",
        "## Understat (archive)",
        "",
        f"- {len(us):,} player-season rows, {us.understat_id.nunique():,} players",
        "",
        cov.pivot(index="season", columns="league", values="status").to_markdown(),
        "",
        f"- Match rate to Transfermarkt: {(m.confidence != 'unmatched').mean():.1%} "
        f"(>= 450 min: {(m[m.minutes >= 450].confidence != 'unmatched').mean():.1%})",
        f"- Season matches contradicting the player-level majority (dropped downstream): "
        f"{int(((m.confidence != 'unmatched') & ~m.agrees_with_player_map).sum())}",
        "",
    ]
    return "\n".join(lines)


def write_report() -> str:
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    text = build_report()
    REPORT.write_text(text, encoding="utf-8")
    return str(REPORT)
