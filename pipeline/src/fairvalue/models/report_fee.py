"""Reports for Step 5: expected-fee model card (+ club audit) and Hidden Gems backtest. Aggregates only."""

from __future__ import annotations

import json

import pandas as pd

from fairvalue.config import DATA_DIR, REPO_ROOT
from fairvalue.io import read_table

FEE_CARD = REPO_ROOT / "reports" / "models" / "expected_fee_model_card.md"
GEMS = REPO_ROOT / "reports" / "models" / "hidden_gems_backtest.md"
COLS = ["n", "mae_log", "r2_log_fee", "median_ape", "within_25pct", "within_50pct", "bias_log"]


def _pct(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    df = df.copy()
    for c in cols:
        df[c] = (df[c].astype(float) * 100).round(1).astype(str) + "%"
    return df


def _fee_card(run: dict) -> str:
    rows = {f"Baseline: {k}": v for k, v in run["baselines"].items()}
    rows |= {f"Ridge{' (chosen)' if run['chosen'] == 'ridge' else ''}": run["ridge"]["metrics"]}
    rows |= {f"Gradient boosting{' (chosen)' if run['chosen'] == 'gbm' else ''}": run["gbm"]["metrics"]}
    metrics = _pct(pd.DataFrame(rows).T[COLS], ["median_ape", "within_25pct", "within_50pct"])
    ch = run[run["chosen"]]
    by = _pct(pd.DataFrame(ch["by_season"]).T[["n", "mae_log", "median_ape", "bias_log"]], ["median_ape"])
    by.index = [f"{s}/{str(int(s) + 1)[-2:]}" for s in by.index]
    cov = ch["coverage"]
    band = _pct(pd.DataFrame(cov["by_mv_band"]).T, ["coverage80"])

    fees = read_table("outputs", "fee_predictions")
    pub = fees[fees.reliability != "Insufficient"]
    labels = pub.label.value_counts().rename("transfers").to_frame()
    rel = fees.reliability.value_counts().rename("transfers").to_frame()

    audit = read_table("outputs", "club_audit")
    ranked = audit[(audit.period == "all") & audit.ranked].copy()
    show = ["club_name", "n_assessed", "total_fee_eur", "total_expected_eur", "price_ratio", "price_ratio_lo80",
            "price_ratio_hi80", "outcome_median_mv_change_12m"]  # fmt: skip

    def fmt(d: pd.DataFrame) -> str:
        d = d[show].copy()
        for c in ["total_fee_eur", "total_expected_eur"]:
            d[c] = (d[c] / 1e6).round(0).astype(int).astype(str) + "M"
        for c in ["price_ratio", "price_ratio_lo80", "price_ratio_hi80"]:
            d[c] = d[c].round(2)
        d["outcome_median_mv_change_12m"] = (d.outcome_median_mv_change_12m * 100).round(0).astype(str) + "%"
        return d.to_markdown(index=False)

    lowest = ranked.sort_values("price_ratio_hi80").head(10)
    highest = ranked.sort_values("price_ratio_lo80", ascending=False).head(10)
    return "\n".join([
        "# Model card: Expected Fee",
        "",
        f"*Generated by `fairvalue train-fee` on {run['created_at']}. All metrics are walk-forward by transfer "
        "season: each transfer is scored by a model trained only on earlier seasons.*",
        "",
        "## What it estimates",
        "",
        "The fee that transfers with comparable public information **at the transfer date** typically "
        "commanded. A transfer premium is fee − expected fee. A transfer is only labelled when its fee falls "
        "outside the 80% range (notable) or 95% range (unusual). Contract length, release clauses, add-ons, "
        "competition between clubs and agent terms are unobserved and sit inside the premium.",
        "",
        "- **Target:** log(fee ÷ market value before the transfer). Expected fee = market value × exp(prediction).",
        f"- **Data:** {run['rows']:,} paid transfers 2015/16–2026 (to 6 Jul 2026) with a market value at most "
        "365 days old.",
        "- **Features (all point-in-time):** market value and 12-month trend; performance-implied relative value "
        "for the last finished season; age, position; buyer's fees paid and seller's fees received in the "
        "previous 365 days; buyer and seller league; window and deadline week; recent playing time; market "
        "premium level (median fee/value ratio of the previous 12 months).",
        "",
        "## Accuracy",
        "",
        metrics.to_markdown(),
        "",
        "*Errors are on fees in euros (market value cancels, so they equal errors on the premium). r2_log_fee is "
        "R² on log fee, where market value alone already explains most of the variance; the question is how "
        f"much the model adds.* {run['selection_reason']}.",
        "",
        "### By season (chosen model)",
        "",
        by.to_markdown(),
        "",
        "### Interval calibration (chosen model)",
        "",
        f"80% coverage **{cov['coverage80']:.1%}**, 95% coverage **{cov['coverage95']:.1%}** (n = {cov['n']:,}); "
        f"median 80% range spans ×{cov['median_width80_ratio']} (top ÷ bottom).",
        "",
        band.rename_axis("market value band").to_markdown(),
        "",
        "## Published classifications",
        "",
        rel.to_markdown(),
        "",
        labels.to_markdown(),
        "",
        "## Club Transfer Audit (2015/16–2026, clubs with ≥ 8 assessed purchases)",
        "",
        "price_ratio = total fees ÷ total expected fees, with an 80% bootstrap range over the club's transfers "
        "(transfer-level model uncertainty isn't included, so the true uncertainty is wider). The outcome "
        "column is the median market-value change 12 months after signing: **an outcome, not used by any "
        "model**. Price efficiency isn't sporting success.",
        "",
        "Lowest price ratios (sorted by the upper end of the range, so small lucky samples don't top the list):",
        "",
        fmt(lowest),
        "",
        "Highest price ratios (sorted by the lower end of the range):",
        "",
        fmt(highest),
        "",
    ])  # fmt: skip


def _gems(run: dict) -> str:
    b = run["gems_backtest"]

    def row(name: str, s: dict) -> dict:
        return {"group": name, "players": s.get("n"), "median excess change": f"{s.get('median_excess_pct', '–')}%",
                "80% CI": str(s.get("ci80_pct", "–")), "share beating peers": s.get("share_beating_peers")}  # fmt: skip

    pooled = pd.DataFrame([
        row("Potential undervaluation (both strengths)", b["pooled"]["under"]),
        row("Strong signal of potential undervaluation", b["strong_signal_only"]),
        row("Within expected range", b["pooled"]["within"]),
        row("Market premium (both strengths)", b["pooled"]["premium"]),
    ])  # fmt: skip
    seasons = pd.DataFrame({
        f"{s}/{str(int(s) + 1)[-2:]}": {
            "undervaluation: n": v["under"].get("n"),
            "undervaluation: median excess %": v["under"].get("median_excess_pct"),
            "premium: n": v["premium"].get("n"),
            "premium: median excess %": v["premium"].get("median_excess_pct"),
        } for s, v in b["by_season"].items()
    }).T  # fmt: skip
    under = b["pooled"]["under"]
    verdict = (
        "Flagged players **did** gain more value than comparable peers over the next 12 months"
        if under.get("ci80_pct", [0, 0])[0] > 0
        else "The evidence that flagged players gain more value than peers is **not conclusive**"
    )
    return "\n".join([
        "# Hidden Gems backtest",
        "",
        f"*Generated by `fairvalue train-fee` on {run['created_at']}. Published as is, whatever it shows.*",
        "",
        "**Question:** did players labelled *potential undervaluation* (peer-relative, reliability High or "
        "Moderate) see their market value rise more than comparable players over the following 12 months?",
        "",
        "**Method:** for every walk-forward season, outcome = change from the post-season market value to the "
        "value ≈12 months later (±90 days). Each player's change is compared with the median change of "
        "*within expected range* players in the same season × position group × age band × value tercile "
        "(\"excess change\"), which controls for young and cheap players rising more on average. 80% "
        "confidence interval by bootstrap.",
        "",
        f"{b['players_with_label']:,} labelled player-seasons; {b['players_with_outcome']:,} with an observed outcome.",
        "",
        pooled.to_markdown(index=False),
        "",
        f"**Reading:** {verdict} (median excess {under.get('median_excess_pct')}%, 80% CI {under.get('ci80_pct')}).",
        "",
        "### By season",
        "",
        seasons.to_markdown(),
        "",
        "## Caveats",
        "",
        "- Market values are crowd opinion: a rise means the crowd revised its view, not that the player was "
        "objectively worth more. Part of any effect can be the crowd catching up with the same public "
        "statistics.",
        "- Survivors only: players without a later valuation (retired, moved outside coverage) have no outcome.",
        "- Regression to the mean: a market value that was unusually low for any reason tends to drift back. "
        "Comparing against peers in the same value tercile reduces, but doesn't remove, this effect.",
        "- This tests market-value movement, not sporting performance or resale profit.",
        "",
    ])  # fmt: skip


def write_reports() -> list[str]:
    run = json.loads((DATA_DIR / "outputs" / "fee_run.json").read_text(encoding="utf-8"))
    FEE_CARD.parent.mkdir(parents=True, exist_ok=True)
    FEE_CARD.write_text(_fee_card(run), encoding="utf-8")
    GEMS.write_text(_gems(run), encoding="utf-8")
    return [str(FEE_CARD), str(GEMS)]
