"""Generate reports/models/piv_model_card.md from data/outputs/piv_run.json (aggregates only)."""

from __future__ import annotations

import json

import pandas as pd

from fairvalue.config import DATA_DIR, REPO_ROOT
from fairvalue.io import read_table

REPORT = REPO_ROOT / "reports" / "models" / "piv_model_card.md"


def _metrics_table(tier: dict) -> str:
    rows = {"Naive baseline (median by position x age)": tier["baseline"]}
    rows |= {f"Ridge{' (chosen)' if tier['chosen'] == 'ridge' else ''}": tier["ridge"]["metrics"]}
    rows |= {f"Gradient boosting{' (chosen)' if tier['chosen'] == 'gbm' else ''}": tier["gbm"]["metrics"]}
    df = pd.DataFrame(rows).T[["n", "mae_log", "r2_log", "median_ape", "within_25pct", "within_50pct", "bias_log"]]
    for c in ["median_ape", "within_25pct", "within_50pct"]:
        df[c] = (df[c].astype(float) * 100).round(1).astype(str) + "%"
    return df.to_markdown()


def _season_table(tier: dict) -> str:
    k = tier["chosen"]
    by = pd.DataFrame(tier[k]["by_season"]).T[["n", "mae_log", "r2_log", "median_ape", "bias_log"]]
    by["median_ape"] = (by.median_ape.astype(float) * 100).round(1).astype(str) + "%"
    by.index = [f"{s}/{str(int(s) + 1)[-2:]}" for s in by.index]
    return by.to_markdown()


def _coverage_table(tier: dict) -> str:
    cov = tier[tier["chosen"]]["coverage"]
    g = pd.DataFrame(cov["by_group"]).T
    g["coverage80"] = (g.coverage80.astype(float) * 100).round(1).astype(str) + "%"
    head = (f"Overall: 80% interval coverage **{cov['coverage80']:.1%}**, 95% coverage **{cov['coverage95']:.1%}** "
            f"(n = {cov['n']:,}); median 80% interval spans a factor of **{cov['median_width80_ratio']}x** "
            f"(top ÷ bottom).")  # fmt: skip
    return head + "\n\n" + g.rename_axis("minutes band / line").to_markdown()


def write_report() -> str:
    run = json.loads((DATA_DIR / "outputs" / "piv_run.json").read_text(encoding="utf-8"))
    preds = read_table("outputs", "piv_predictions")
    parts = [
        "# Model card: Performance-Implied Value (PIV)",
        "",
        f"*Generated by `fairvalue train-piv` on {run['created_at']} (pipeline {run['pipeline_version']}). "
        "All metrics are walk-forward: every number comes from a model that never saw the season it scores.*",
        "",
        "## What it estimates",
        "",
        "The market value that players with this season's measurable profile (performance, minutes, age, "
        "position, league, team strength) typically carry **in the same summer's market**. It isn't a "
        "'true value' and it isn't a price forecast. The gap between a player's actual market value and this "
        "range is a signal for further scouting, not a verdict.",
        "",
        "- **Target:** log Transfermarkt market value at the first valuation within 120 days after the season "
        "ends, divided by that summer's market index (median value of eligible big-five outfield players).",
        "- **Unit:** player × league × season, outfield players with ≥ 900 league minutes.",
        "- **Validation:** walk-forward by season; hyperparameters chosen on the season before the test season; "
        "intervals calibrated on the previous three seasons' out-of-sample errors (group-wise split conformal).",
        "- **Excluded by design:** the player's own market value (circular), nationality, and snapshot fields "
        "(caps, contract, current club).",
        "",
    ]
    for tier, title in [
        ("full", "Full tier: big five with xG data"),
        ("basic", "Basic tier: Transfermarkt data"),
    ]:
        t = run["tiers"][tier]
        parts += [
            f"## {title}",
            "",
            f"{t['rows']:,} player-seasons. **Chosen model: {t['chosen']}.** Selection rule: boosting must "
            f"beat Ridge by ≥ 5% MAE (log) without worse calibration. {t['selection_reason']}.",
            "",
            "### Accuracy (pooled walk-forward seasons)",
            "",
            _metrics_table(t),
            "",
            "*median_ape: typical % error in euros. within_X: share of players whose estimate is within ±X% "
            "of their actual market value. bias_log > 0 means the model under-estimates on average.*",
            "",
            "### By season (chosen model)",
            "",
            _season_table(t),
            "",
            "### Interval calibration (chosen model)",
            "",
            _coverage_table(t),
            "",
        ]
    pub = preds[preds.reliability != "Insufficient"]
    rel = preds.groupby(["model_tier", "reliability"]).size().unstack(fill_value=0)
    labels = pub.groupby(["model_tier", "gap_label"]).size().unstack(fill_value=0)
    parts += [
        "## Published predictions",
        "",
        "Reliability tiers (rules in docs/PRODUCT_SPEC.md 2.3):",
        "",
        rel.to_markdown(),
        "",
        "Gap labels (actual market value vs the PIV range). By construction about 10% of players fall below "
        "and 10% above the 80% range each season, so a label marks the most unusual cases, not a verdict:",
        "",
        labels.to_markdown(),
        "",
        "## Known limitations",
        "",
        "- The target is crowd opinion (Transfermarkt), so the model learns how the market prices profiles, "
        "including its biases (reputation, league prestige).",
        "- No defensive or goalkeeping metrics: centre-backs and full-backs are valued mostly on playing time, "
        "team strength and age (reliability downgraded); goalkeepers are excluded.",
        "- Contract length, injuries and off-pitch factors are unobserved and sit in the gap.",
        "- Position is today's label unless that season's Understat usage contradicts it.",
        "- Understat is missing for 10 big-five league-seasons and for 2025/26; those rows use the basic tier.",
        "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(parts), encoding="utf-8")
    return str(REPORT)
