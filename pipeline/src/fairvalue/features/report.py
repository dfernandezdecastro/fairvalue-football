"""reports/features/feature_summary.md - aggregate counts only (safe to commit)."""

from __future__ import annotations

import pandas as pd

from fairvalue.config import REPO_ROOT
from fairvalue.features.positions import GROUP_LABELS
from fairvalue.io import read_table

REPORT = REPO_ROOT / "reports" / "features" / "feature_summary.md"
STEPS = {
    "F1": "Paid transfer since 2015/16, not a probable paid loan",
    "F2": "+ big-five club buying or selling",
    "F3": "+ played in a big-five league in the feature season",
    "F4": "+ that league-season exists in the Understat archive",
    "F5": "+ matched to an Understat player",
    "F6": "+ >= 900 Understat minutes in the feature season",
    "F7": "+ market value <= 365 days old -> usable (full tier)",
}


def write_report() -> str:
    tf = read_table("features", "transfer_features")
    ps = read_table("features", "player_season_features")
    prof = read_table("features", "profiles")
    pr = read_table("features", "shrinkage_priors")

    funnel = pd.DataFrame({"step": list(STEPS.values()), "transfers": [int(tf[k].sum()) for k in STEPS]})
    funnel.loc[len(funnel)] = ["Usable (basic tier): F1 + >= 900 TM minutes in prior 365 days + fresh value",
                               int(tf.usable_basic.sum())]  # fmt: skip
    elig = prof[prof.eligible]
    tiers = elig.groupby(["season", "data_tier"]).size().unstack(fill_value=0)
    groups = elig.groupby("position_group").size().rename(index=GROUP_LABELS).rename("player-seasons")
    big5 = pr[pr.peer_scope == "big5"].groupby(["metric", "k_source"]).prior_minutes.median().round(0)

    text = "\n".join([
        "# Feature summary",
        "",
        "*Generated by `fairvalue features`. Aggregates only.*",
        "",
        "## Transfer funnel (all features computed as of the transfer date)",
        "",
        funnel.to_markdown(index=False),
        "",
        f"- Transfers whose most recent season had not finished by the transfer date, so features use "
        f"the season before: **{int((tf.feat_season == tf.season - 2).sum())}** (mostly summer 2020, COVID).",
        "",
        "## Player-season rows eligible for profiles (>= 900 league minutes)",
        "",
        tiers.to_markdown(),
        "",
        groups.to_frame().to_markdown(),
        "",
        f"- Position from Understat season usage (overriding the current Transfermarkt label): "
        f"{int((ps.position_source == 'understat_season').sum())} rows; confirmed by Understat: "
        f"{int((ps.position_source == 'tm_current_confirmed').sum())}; current label only: "
        f"{int((ps.position_source == 'tm_current').sum())}.",
        "",
        "## Shrinkage prior strength, big five (median minutes of 'virtual' average play)",
        "",
        big5.rename("median prior minutes").to_frame().to_markdown(),
        "",
    ])  # fmt: skip
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(text, encoding="utf-8")
    return str(REPORT)
